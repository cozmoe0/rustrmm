#!/usr/bin/env node
/*
 * Generates TypeScript types for the console from the server's OpenAPI 3.1 document.
 *
 *   npm run gen:api                         # from the committed snapshot web/openapi.json
 *   npm run gen:api -- --from <url|file>    # from a running server or another file
 *   npm run gen:api -- --from <url> --save  # …and refresh the committed snapshot too
 *   npm run gen:api -- --from <url> --check # CI: fail when snapshot or types are stale
 *
 * Output: src/lib/api/openapi.gen.ts. The hand-written types in src/lib/api/types.ts stay the
 * console's source of truth for now; the generated file is there to diff against and adopt
 * gradually. Self-signed dev servers: set NODE_TLS_REJECT_UNAUTHORIZED=0 for the download only.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SNAPSHOT = resolve(root, 'openapi.json')
const OUTPUT = resolve(root, 'src/lib/api/openapi.gen.ts')
const HEADER = `/*
 * Generated by \`npm run gen:api\` from the server's OpenAPI document (web/openapi.json).
 * Do not edit by hand; regenerate after API changes. Hand-written types live in ./types.ts.
 */
/* eslint-disable */
`

function parseArgs(argv) {
  const args = { from: null, save: false, check: false, strict: false }
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index]
    if (arg === '--from') args.from = argv[++index] ?? null
    else if (arg.startsWith('--from=')) args.from = arg.slice('--from='.length)
    else if (arg === '--save') args.save = true
    else if (arg === '--check') args.check = true
    else if (arg === '--strict') args.strict = true
    else if (!arg.startsWith('-') && !args.from) args.from = arg
    else {
      console.error(`Unknown argument: ${arg}`)
      process.exit(2)
    }
  }
  return args
}

async function loadSpec(source) {
  if (/^https?:\/\//.test(source)) {
    const response = await fetch(source, { headers: { accept: 'application/json' } })
    if (!response.ok) throw new Error(`GET ${source} answered ${response.status}`)
    return response.json()
  }
  const path = resolve(process.cwd(), source)
  if (!existsSync(path)) throw new Error(`${path} does not exist`)
  return JSON.parse(readFileSync(path, 'utf8'))
}

/** Stable JSON so the committed snapshot only changes when the API does. */
function canonical(value) {
  if (Array.isArray(value)) return value.map(canonical)
  if (value && typeof value === 'object') return Object.fromEntries(Object.keys(value).sort().map((key) => [key, canonical(value[key])]))
  return value
}

function warn(message) {
  if (process.env.GITHUB_ACTIONS) console.log(`::warning title=OpenAPI types::${message}`)
  else console.warn(`warning: ${message}`)
}

const args = parseArgs(process.argv.slice(2))
const source = args.from ?? (existsSync(SNAPSHOT) ? SNAPSHOT : null)
if (!source) {
  console.error('No spec snapshot (web/openapi.json) yet. Generate from a running server, for example:')
  console.error('  NODE_TLS_REJECT_UNAUTHORIZED=0 npm run gen:api -- --from https://localhost:8443/api/openapi.json --save')
  process.exit(1)
}

const spec = await loadSpec(source)
if (typeof spec?.openapi !== 'string' || !spec.openapi.startsWith('3.')) throw new Error(`${source} is not an OpenAPI 3 document`)
const snapshot = `${JSON.stringify(canonical(spec), null, 2)}\n`
const types = HEADER + astToString(await openapiTS(spec, { alphabetize: true, exportType: true }))

if (args.check) {
  const stale = []
  const missing = []
  for (const [path, contents, label] of [
    [SNAPSHOT, snapshot, 'web/openapi.json'],
    [OUTPUT, types, 'web/src/lib/api/openapi.gen.ts'],
  ]) {
    if (!existsSync(path)) missing.push(label)
    else if (readFileSync(path, 'utf8').replace(/\r\n/g, '\n') !== contents) stale.push(label)
  }
  if (missing.length) {
    // Bootstrap state: nothing committed yet. Write the files so CI can upload them as an artifact.
    writeFileSync(SNAPSHOT, snapshot)
    writeFileSync(OUTPUT, types)
    warn(`Not committed yet: ${missing.join(', ')}. Run \`npm run gen:api -- --from <server>/api/openapi.json --save\` and commit both files.`)
    process.exit(args.strict ? 1 : 0)
  }
  if (stale.length) {
    console.error(`Out of date: ${stale.join(', ')}. Regenerate with \`npm run gen:api -- --from <server>/api/openapi.json --save\` and commit the result.`)
    process.exit(1)
  }
  console.log(`OpenAPI snapshot and generated types are up to date (${Object.keys(spec.paths ?? {}).length} paths, OpenAPI ${spec.openapi}).`)
  process.exit(0)
}

if (args.save || source === SNAPSHOT) writeFileSync(SNAPSHOT, snapshot)
writeFileSync(OUTPUT, types)
console.log(`Wrote ${OUTPUT.replace(root, 'web')} from ${source === SNAPSHOT ? 'web/openapi.json' : source} (${Object.keys(spec.paths ?? {}).length} paths, OpenAPI ${spec.openapi}).`)
